export type MessageKey = keyof typeof messages.en;
export const translate = (language: Language, key: MessageKey) => messages[language][key];

const vietnameseDishNames: Record<string, { english: string; vietnamese: string }> = {
  'dish-salmon': { english: 'Grilled Salmon', vietnamese: 'Cá hồi nướng' },
  'dish-shrimp': { english: 'Garlic Butter Shrimp', vietnamese: 'Tôm sốt bơ tỏi' },
  'dish-noodles': { english: 'Beef Noodle Bowl', vietnamese: 'Tô mì bò' },
  'dish-rice': { english: 'Garden Fried Rice', vietnamese: 'Cơm chiên rau củ' },
  'dish-cake': { english: 'Chocolate Lava Cake', vietnamese: 'Bánh lava sô-cô-la' },
};

export function translateDishName(language: Language, id: string, name: string): string {
  if (language !== 'vi') return name;
  const translation = vietnameseDishNames[id];
  return translation?.english === name ? translation.vietnamese : name;
}
